// Specs for scripts/check-doc-coverage.js (npm run test:checks): what counts as an export, a field and a doc
// comment, how gaps compare with the baseline, and that an update only removes names. Synthetic sources only.
"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { describe, it } = require("node:test");
const {
	FIELD_AREAS,
	areaOf,
	baselineOf,
	compareKind,
	gapsInSource,
	isGeneratedSource,
	isSourceFile,
	scan,
	shrinkKind,
} = require("./check-doc-coverage.js");

const names = (gaps) => gaps.map((g) => g.name);

describe("gapsInSource", () => {
	it("lists exported declarations without a doc comment, by name and line", () => {
		const src = [
			'import { a } from "./a";',
			"",
			"/** Documented. */",
			"export function documented(): void {}",
			"export function bare(): void {}",
			"// a line comment is not a doc comment",
			"export const TABLE = [1, 2];",
			"/* neither is a plain block comment */",
			"export interface Shape {",
			"\tx: number;",
			"}",
			"export type Alias = number;",
			"export class Thing {}",
			"export enum Kind {}",
			"function local(): void {}",
			"const hidden = 1;",
		].join("\n");
		const gaps = gapsInSource("a.ts", src, false);
		assert.deepEqual(names(gaps.exports), ["bare", "TABLE", "Shape", "Alias", "Thing", "Kind"]);
		assert.equal(gaps.exports[0].line, 5);
		assert.deepEqual(gaps.fields, []);
	});

	it("counts an overloaded function once, by its first signature", () => {
		const overloads = [
			"export function f(a: number): number;",
			"export function f(a: string): string;",
			"export function f(a: unknown): unknown {",
			"\treturn a;",
			"}",
		];
		assert.deepEqual(names(gapsInSource("a.ts", overloads.join("\n"), false).exports), ["f"]);
		assert.deepEqual(gapsInSource("a.ts", `/** Doubles. */\n${overloads.join("\n")}`, false).exports, []);
		// Two separate functions that happen to follow each other are still two.
		const two = "export function f(): void {}\nexport function f2(): void {}";
		assert.deepEqual(names(gapsInSource("a.ts", two, false).exports), ["f", "f2"]);
	});

	it("does not count re-exports, and reads TSX", () => {
		const src = ['export * from "./a";', 'export { b } from "./b";', "export const View = () => <frame />;"].join(
			"\n",
		);
		assert.deepEqual(names(gapsInSource("view.tsx", src, false).exports), ["View"]);
	});

	it("gives a module header to the module, not to the declaration under it", () => {
		const header = ["/**", " * What this file is for.", " *", " * @module", " */"].join("\n");
		assert.deepEqual(names(gapsInSource("a.ts", `${header}\nexport const A = 1;`, false).exports), ["A"]);
		assert.deepEqual(gapsInSource("a.ts", `${header}\n\n/** A. */\nexport const A = 1;`, false).exports, []);
		// Without the tag the comment is the declaration's own (a one-declaration file needs no header).
		assert.deepEqual(gapsInSource("a.ts", "/** What A is for. */\nexport const A = 1;", false).exports, []);
		// A comment that only mentions the word is not a header.
		assert.deepEqual(
			gapsInSource("a.ts", "/** See the `@module` rule. */\nexport const A = 1;", false).exports,
			[],
		);
	});

	it("lists the uncommented members of exported interfaces only when asked", () => {
		const src = [
			"/** The state. */",
			"export interface State {",
			"\t/** Ticks since the run began. */",
			"\ttick: number;",
			"\thp: number;",
			"\tstep(dt: number): void;",
			"\t[key: string]: unknown;",
			"}",
			"interface Private {",
			"\tx: number;",
			"}",
			"/** A class. */",
			"export class Holder {",
			"\tvalue = 1;",
			"}",
		].join("\n");
		assert.deepEqual(names(gapsInSource("s.ts", src, true).fields), ["State.hp", "State.step", "State.(index)"]);
		assert.deepEqual(gapsInSource("s.ts", src, false).fields, []);
	});
});

describe("areas and files", () => {
	it("names an area by its first directories", () => {
		assert.equal(areaOf("shared/sim/combat/arc.ts"), "shared/sim");
		assert.equal(areaOf("shared/sim/rng.ts"), "shared/sim");
		assert.equal(areaOf("shared/network.ts"), "shared");
		assert.equal(areaOf("client/ui/gui.ts"), "client");
		assert.equal(areaOf("server/runtime.server.ts"), "server");
	});

	it("skips specs and declaration files", () => {
		assert.equal(isSourceFile("a.ts"), true);
		assert.equal(isSourceFile("a.tsx"), true);
		assert.equal(isSourceFile("a.spec.ts"), false);
		assert.equal(isSourceFile("a.spec.tsx"), false);
		assert.equal(isSourceFile("a.d.ts"), false);
		assert.equal(isSourceFile("a.luau"), false);
	});

	it("knows a generated source by its first two lines", () => {
		assert.equal(
			isGeneratedSource(
				"// GENERATED by `npm run art:build` from art/atlases.json. Do not edit.\nexport const A = 1;",
			),
			true,
		);
		assert.equal(
			isGeneratedSource(
				"/** Generated by `npm run art:build` (docs/UI_ART.md UA3). Do not edit. */\nexport const A = 1;",
			),
			true,
		);
		assert.equal(
			isGeneratedSource("/**\n * Generated by `npm run art:build`. Do not edit.\n */\nexport const A = 1;"),
			true,
		);
		assert.equal(
			isGeneratedSource("/**\n * A module.\n * Generated by x. Do not edit.\n */\nexport const A = 1;"),
			false,
		);
		assert.equal(isGeneratedSource("// Do not edit lightly.\nexport const A = 1;"), false);
		assert.equal(isGeneratedSource("export const A = 1; // generated by x, do not edit\n"), true);
	});

	it("scans a tree: fields only in the field areas, generated fixtures never", () => {
		const root = fs.mkdtempSync(path.join(os.tmpdir(), "kv-doc-coverage-"));
		const write = (rel, text) => {
			fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
			fs.writeFileSync(path.join(root, rel), text);
		};
		const shape = "export interface Shape {\n\tx: number;\n}\n";
		write("shared/sim/state.ts", shape);
		write("shared/view/props.ts", shape);
		write("shared/sim/state.spec.ts", shape);
		write("shared/fixtures-generated/rng.ts", shape);
		write("client/ui/gui.tsx", "export const Gui = 1;\n");
		write(
			"shared/theme/layout.ts",
			"// GENERATED by `npm run art:build`. Do not edit.\nexport const LAYOUT = 1;\n",
		);
		const scanned = scan(root);
		assert.equal(scanned.files, 3);
		assert.deepEqual(baselineOf(scanned), {
			exports: { client: ["Gui"], "shared/sim": ["Shape"], "shared/view": ["Shape"] },
			fields: { "shared/sim": ["Shape.x"] },
		});
		assert.equal(scanned.exports["shared/sim"][0].file, "shared/sim/state.ts");
		assert.ok(FIELD_AREAS.includes("shared/sim") && !FIELD_AREAS.includes("shared/view"));
	});
});

describe("compareKind", () => {
	const gap = (name) => ({ name, file: "f.ts", line: 1 });

	it("passes the listed gaps and fails a new one, in its area", () => {
		const result = compareKind({ a: [gap("x"), gap("y")], b: [gap("x")] }, { a: ["x", "y"] });
		assert.deepEqual(result.added, [{ area: "b", name: "x", file: "f.ts", line: 1 }]);
		assert.deepEqual(result.closed, []);
	});

	it("reports a listed gap that is gone as closed", () => {
		const result = compareKind({ a: [gap("x")] }, { a: ["x", "y"], gone: ["z"] });
		assert.deepEqual(result.added, []);
		assert.deepEqual(result.closed, [
			{ area: "a", name: "y" },
			{ area: "gone", name: "z" },
		]);
	});

	it("counts a repeated name as many times as it is listed", () => {
		assert.equal(compareKind({ a: [gap("x"), gap("x")] }, { a: ["x", "x"] }).added.length, 0);
		assert.equal(compareKind({ a: [gap("x"), gap("x")] }, { a: ["x"] }).added.length, 1);
		assert.equal(compareKind({ a: [gap("x")] }, { a: ["x", "x"] }).closed.length, 1);
	});

	it("an area at zero stays at zero", () => {
		assert.equal(compareKind({ a: [gap("fresh")] }, { a: [] }).added.length, 1);
	});
});

describe("shrinkKind", () => {
	const gap = (name) => ({ name, file: "f.ts", line: 1 });

	it("removes closed gaps and never adds one", () => {
		const next = shrinkKind({ a: [gap("x"), gap("fresh")], b: [gap("other")] }, { a: ["x", "y"], c: ["z"] });
		assert.deepEqual(next, { a: ["x"], c: [] });
	});

	it("keeps as many of a repeated name as are still gaps", () => {
		assert.deepEqual(shrinkKind({ a: [gap("x")] }, { a: ["x", "x"] }), { a: ["x"] });
	});
});
