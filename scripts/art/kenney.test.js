// Specs for the atlas pipeline's kenney group (docs/KENNEY_DECOR.md KN9; npm run test:art): Kenney's reprojected pieces
// cut on their given pivots and packed into ONE sheet of their own (rect cuts, no two sharing a pixel, an outline on
// request), the source files the lock hashes, the generated kenneyLayout.ts, `--only kenney`, and (when art/vendor holds
// the renders) that the committed kenneyLayout.ts is what the build writes. Synthetic PNGs through the pipeline's cache.
"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { describe, it } = require("node:test");
const { PNG } = require("pngjs");
const A = require("./build-atlases.js");

const ROOT = path.join(__dirname, "..", "..");
const LAYOUT_FILE = path.join(ROOT, "src", "shared", "theme", "packs", "vale", "kenneyLayout.ts");
const CONFIG = JSON.parse(fs.readFileSync(path.join(ROOT, "art", "atlases.json"), "utf8"));

function syntheticPng(rel, w, h, paint) {
	const png = new PNG({ width: w, height: h });
	for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) png.data.set(paint(x, y) || [0, 0, 0, 0], (y * w + x) * 4);
	const back = PNG.sync.read(PNG.sync.write(png));
	A.sourceCache.set(rel, { w: back.width, h: back.height, data: new Uint8Array(back.data) });
}

const WOOD = [140, 96, 60, 255];
const WORLD = {
	noiseAlpha: 2,
	shadowRgb: 4,
	pad: 2,
	footBand: 3,
	atlas: { name: "decor-atlas", maxSize: 1024 },
	pieces: {},
};

/** A group over synthetic renders: a 6 x 4 block at (2, 3) (pivot 5, 6.5) with an outline, a 3 x 3 flat one. */
function group() {
	syntheticPng("k/table/a.png", 10, 9, (x, y) => (x >= 2 && x < 8 && y >= 3 && y < 7 ? WOOD : null));
	syntheticPng("k/rug/a.png", 7, 7, (x, y) => (x >= 2 && x < 5 && y >= 2 && y < 5 ? WOOD : null));
	return {
		atlas: { name: "k-decor", maxSize: 64 },
		pixelsPerTile: 29.6,
		pieces: {
			$comment: "synthetic",
			"k-table": { file: "k/table/a.png", pivot: [5, 6.5], outline: true },
			"k-rug": { file: "k/rug/a.png", pivot: [3.5, 3.5] },
		},
	};
}

describe("kenney group", () => {
	it("cuts every piece on its pivot and packs them into one sheet of their own", () => {
		const k = A.buildKenney(group(), WORLD, undefined);
		assert.deepEqual(
			k.atlases.map((a) => a.file),
			["k-decor.png"],
		);
		const t = k.layouts["k-table"];
		const r = k.layouts["k-rug"];
		for (const l of [t, r]) {
			assert.equal(l.kind, "image");
			assert.equal(l.file, "k-decor.png");
			assert.equal(l.pixelsPerTile, 29.6);
			assert.ok(l.rect.x + l.rect.w <= l.w && l.rect.y + l.rect.h <= l.h);
		}
		// the 6 x 4 block cropped and padded by 2: 10 x 8, the pivot moved with the crop
		assert.deepEqual([t.rect.w, t.rect.h], [10, 8]);
		assert.deepEqual(t.pivot, { x: 5, y: 5.5 });
		assert.ok(Array.isArray(t.outline) && t.outline.length >= 4);
		assert.equal(r.outline, undefined);
		// no two pieces share a pixel
		const overlap =
			t.rect.x < r.rect.x + r.rect.w &&
			r.rect.x < t.rect.x + t.rect.w &&
			t.rect.y < r.rect.y + r.rect.h &&
			r.rect.y < t.rect.y + t.rect.h;
		assert.equal(overlap, false);
	});

	it("names its sources for the lock, refuses unknown keys, and is an --only group", () => {
		assert.deepEqual(A.kenneySourceFiles(group()), ["k/rug/a.png", "k/table/a.png"]);
		assert.deepEqual(A.kenneySourceFiles(undefined), []);
		const bad = group();
		bad.pieces["k-rug"].scale = 2;
		assert.throws(() => A.buildKenney(bad, WORLD, undefined), /unknown key scale/);
		const noPivot = group();
		delete noPivot.pieces["k-rug"].pivot;
		assert.throws(() => A.buildKenney(noPivot, WORLD, undefined), /pivot/);
		assert.equal(A.onlyGroup(["node", "x", "--only", "kenney"]), "kenney");
		assert.deepEqual(A.onlyGroupSourceFiles({ kenney: group() }, "kenney"), ["k/rug/a.png", "k/table/a.png"]);
	});

	it("writes kenneyLayout.ts in prettier's shape, within 120 columns", () => {
		const text = A.kenneyLayoutModule(A.buildKenney(group(), WORLD, undefined));
		assert.match(text, /^\/\/ GENERATED by `npm run art:build`/);
		assert.match(text, /export const VALE_KENNEY_SHEETS: ReadonlyArray<string> = \["k-decor\.png"\];/);
		assert.match(text, /export const VALE_KENNEY_LAYOUTS: Record<string, ValeWorldImageLayout> = \{/);
		for (const line of text.split("\n")) assert.ok(line.replace(/\t/g, "    ").length <= 120, line);
	});

	it("the committed kenneyLayout.ts is what the build writes (when art/vendor/kenney holds the renders)", (t) => {
		const files = A.kenneySourceFiles(CONFIG.kenney);
		if (!files.every((f) => fs.existsSync(path.join(ROOT, "art", "vendor", f)))) {
			t.skip("art/vendor/kenney/ is not here");
			return;
		}
		for (const f of files) A.sourceCache.delete(f);
		const k = A.buildKenney(CONFIG.kenney, CONFIG.worldArt, undefined);
		assert.equal(A.kenneyLayoutModule(k), fs.readFileSync(LAYOUT_FILE, "utf8"));
	});
});
