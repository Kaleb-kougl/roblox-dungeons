// docs/OPEN_TASKS.md: every unchecked task of every plan in docs/, in one list, so the owner's Studio checks,
// playtests, uploads and device checks can be cleared in batches (docs/CODEBASE_SCALE.md DX11).
//
//   node scripts/open-tasks.js            write docs/OPEN_TASKS.md   (npm run tasks:open)
//
// A task is a markdown line `- [ ] ...` in docs/*.md; the decision log's "... pending" sentences follow in their own
// section (some plans list their owner checks without a checkbox). Its group comes from its own words: Studio / playtest / device
// checks first (what only the owner can do), then uploads and art / audio, then the rest. The list is generated: tick
// the task in its own doc and run this again. Not part of verify (a doc edit should never fail the build).
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const DOCS_DIR = "docs";
const OUT_PATH = "docs/OPEN_TASKS.md";
/** Generated lists and files that only quote tasks. */
const SKIP = new Set(["OPEN_TASKS.md", "FACTS.md"]);
const DECISIONS_PATH = "docs/DECISIONS.md";
const SUMMARY_CHARS = 150;

/** Groups in list order; a task goes to the first whose pattern its text matches. */
const GROUPS = [
	{ id: "studio", title: "Studio checks, playtests and device checks", pattern: /\bstudio\b|playtest|play test|\bdevice|\bphone\b|\bsign[- ]off\b|\bby ear\b/i },
	{ id: "assets", title: "Uploads, art and audio", pattern: /\bupload|\bart\b|\baudio\b|\bsound|\bclip|\bicons?\b|\bsheet/i },
	{ id: "other", title: "Everything else", pattern: /./ },
];

/** The open tasks of one doc's text: { line, id, summary, group }. */
function openTasks(text) {
	const tasks = [];
	const lines = text.split("\n");
	for (let i = 0; i < lines.length; i++) {
		const m = /^\s*- \[ \] (.*)$/.exec(lines[i]);
		if (!m) continue;
		// A task's text runs over its continuation lines (indented, not a new list item) up to a blank line.
		let body = m[1];
		for (let j = i + 1; j < lines.length; j++) {
			if (lines[j].trim() === "" || /^\s*([-*] |\d+\. |#|\|)/.test(lines[j]) || !/^\s/.test(lines[j])) break;
			body += " " + lines[j].trim();
		}
		const idMatch = /^\*\*([A-Za-z]{1,4}-?[A-Za-z]?\d+[a-z]?)\b/.exec(body);
		const plain = body.replace(/\*\*/g, "").replace(/\s+/g, " ").trim();
		const group = GROUPS.find((g) => g.pattern.test(plain)).id;
		tasks.push({
			line: i + 1,
			id: idMatch ? idMatch[1] : "",
			summary: plain.length > SUMMARY_CHARS ? plain.slice(0, SUMMARY_CHARS - 1).trimEnd() + "…" : plain,
			group,
		});
	}
	return tasks;
}

/**
 * The decision log's pending notes: for every entry (a top-level `- **Title.** ...` bullet) the sentences that say
 * something is pending. { title, notes } in the log's order.
 */
function pendingNotes(text) {
	const out = [];
	const lines = text.split("\n");
	let entry = undefined;
	const flush = () => {
		if (entry === undefined) return;
		const body = entry.replace(/\s+/g, " ").trim();
		const title = /^- \*\*(.+?)\*\*/.exec(body);
		const notes = body
			.split(/(?<=[.;])\s+(?=[A-Z`*(])/)
			.filter((sentence) => /\bpending\b/i.test(sentence))
			.map((sentence) => sentence.replace(/\*\*/g, "").trim());
		if (title && notes.length > 0) out.push({ title: title[1].replace(/[.:]$/, ""), notes });
		entry = undefined;
	};
	for (const line of lines) {
		if (/^- \*\*/.test(line)) {
			flush();
			entry = line;
		} else if (entry !== undefined && (/^\s+\S/.test(line) || line.trim() === "")) {
			entry += " " + line.trim();
		} else {
			flush();
		}
	}
	flush();
	return out;
}

/** The whole file from { doc, tasks } rows and the log's pending notes (pure: the spec feeds it synthetic docs). */
function render(docs, pending = []) {
	const total = docs.reduce((n, d) => n + d.tasks.length, 0);
	const out = [
		"# Open tasks",
		"",
		"Generated by `npm run tasks:open` from the unchecked `- [ ]` tasks in `docs/*.md`. **Never edit by hand**: tick a",
		"task in its own doc, then run the script again (docs/CODEBASE_SCALE.md DX11).",
		"",
		`${total} open task${total === 1 ? "" : "s"} in ${docs.filter((d) => d.tasks.length > 0).length} docs.`,
		"",
	];
	for (const g of GROUPS) {
		const rows = docs
			.map((d) => ({ doc: d.doc, tasks: d.tasks.filter((t) => t.group === g.id) }))
			.filter((d) => d.tasks.length > 0);
		const count = rows.reduce((n, d) => n + d.tasks.length, 0);
		out.push(`## ${g.title} (${count})`, "");
		if (count === 0) out.push("None.", "");
		for (const d of rows) {
			out.push(`### ${d.doc}`, "");
			for (const t of d.tasks) out.push(`- [ ] ${t.summary} (\`docs/${d.doc}\` line ${t.line})`);
			out.push("");
		}
	}
	out.push(`## Marked pending in the decision log (${pending.length} entries)`, "");
	out.push("Sentences of `docs/DECISIONS.md` that say something is pending. When one is done, edit its entry there.", "");
	for (const p of pending) {
		out.push(`- **${p.title}**`);
		for (const note of p.notes) out.push(`  - ${note}`);
	}
	out.push("");
	return out.join("\n");
}

function main() {
	const docs = fs
		.readdirSync(DOCS_DIR)
		.filter((f) => f.endsWith(".md") && !SKIP.has(f))
		.sort()
		.map((doc) => ({ doc, tasks: openTasks(fs.readFileSync(path.join(DOCS_DIR, doc), "utf8")) }));
	const pending = fs.existsSync(DECISIONS_PATH) ? pendingNotes(fs.readFileSync(DECISIONS_PATH, "utf8")) : [];
	fs.writeFileSync(OUT_PATH, render(docs, pending));
	const total = docs.reduce((n, d) => n + d.tasks.length, 0);
	console.log(`open-tasks: ${total} open tasks, ${pending.length} log entries with pending notes -> ${OUT_PATH}`);
	return 0;
}

module.exports = { GROUPS, openTasks, pendingNotes, render };

if (require.main === module) process.exit(main());
