// docs/FACTS.md: the numbers the docs used to copy by hand, generated from the build (docs/CODEBASE_SCALE.md DX10).
//
//   node scripts/facts.js            write docs/FACTS.md           (npm run facts; needs `npm run build` first)
//   node scripts/facts.js --check    fail when the file is stale   (npm run facts:check, part of verify)
//
// The game's values come from the compiled modules (scripts/lune/dump-facts.luau, the spec runner's fake DataModel),
// the locals from scripts/check-luau-locals.js. A decision entry links here instead of quoting a number.
"use strict";

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const { LIMIT, WARN, measure } = require("./check-luau-locals.js");

const FACTS_PATH = "docs/FACTS.md";
/**
 * The locals table lists every compiled module at or above this (not a "top N": that would go stale with every
 * edit of a large module; this changes only when a module nears the limit or one of these few moves).
 */
const WATCH = 150;
/** Roblox's analytics limits per experience (shared/onboarding analyticsCatalog.ts checks the same). */
const ANALYTICS_LIMITS = { customEvents: 100, combinations: 8000 };

function gameFacts() {
	const out = execFileSync("lune", ["run", "scripts/lune/dump-facts.luau"], { encoding: "utf8" });
	return JSON.parse(out);
}

function localsRows(modules) {
	return modules.filter((m) => m.locals >= WATCH);
}

/** The whole file's text from the facts (pure: the spec feeds it synthetic facts). */
function render(facts, modules) {
	const n = (v) => v.toLocaleString("en-US");
	const lines = [
		"# Facts",
		"",
		"Generated by `npm run facts` from the build. **Never edit by hand**: `npm run verify` fails when this file is",
		"stale (`facts:check`); run `npm run build && npm run facts` and commit the result. Decision entries link here",
		"instead of copying a number (docs/CODEBASE_SCALE.md DX10).",
		"",
		"## Game",
		"",
		"| Fact | Value | Where |",
		"|---|---|---|",
		`| \`DAILY.ruleset\` | ${facts.dailyRuleset} | \`shared/daily\` config.ts |`,
		`| \`SIM_BUTTONS\` | ${facts.simButtons} | \`shared/sim\` input.ts |`,
		`| Boons (\`BOON_COUNT\`) | ${facts.boons} | \`shared/sim\` progression |`,
		`| Codex entries | ${facts.codexEntries} | \`shared/codex\` \`CODEX_CATALOG\` |`,
		`| Analytics custom event names | ${facts.analyticsCustomEvents} of ${ANALYTICS_LIMITS.customEvents} | \`shared/onboarding\` \`ANALYTICS_CATALOG\` |`,
		`| Analytics field value combinations | ${n(facts.analyticsCombinations)} of ${n(ANALYTICS_LIMITS.combinations)} | \`analyticsCatalogCombinations()\` |`,
		`| Analytics funnels | ${facts.analyticsFunnels} | \`ANALYTICS_CATALOG\` (funnel + onboarding) |`,
		"",
		"## Theme lists",
		"",
		"| List | Entries |",
		"|---|---|",
		`| \`PORT_AUDIO_EVENTS\` | ${facts.portAudioEvents} |`,
		`| \`REQUIRED_ASSET_IDS\` | ${facts.requiredAssetIds} |`,
		`| \`REQUIRED_STRING_KEYS\` | ${facts.requiredStringKeys} |`,
		`| \`COLOR_ROLES\` | ${facts.colorRoles} |`,
		`| \`ENEMY_ARCHETYPES\` (theme slots) | ${facts.enemyArchetypeSlots} |`,
		"",
		"## Archetype index table",
		"",
		"`archetypeIds()` of the game's registry, by (band, id): the index is hashed and recorded, so no entry ever moves",
		"(`sim/actors.spec.ts` holds the lock).",
		"",
		"| Index | Id |",
		"|---|---|",
		...facts.archetypes.map((id, i) => `| ${i} | \`${id}\` |`),
		"",
		"## Top-level locals",
		"",
		`Luau allows ${LIMIT} local variables at a module's top level; \`check:locals\` fails past it and warns from ${WARN}.`,
		`Every compiled module at or above ${WATCH}:`,
		"",
		"| Module | Top-level locals |",
		"|---|---|",
		...(localsRows(modules).length > 0
			? localsRows(modules).map((m) => `| \`out/${m.file}\` | ${m.locals} |`)
			: ["| (none) | |"]),
		"",
	];
	return lines.join("\n");
}

function main(argv) {
	if (!fs.existsSync("out/shared")) {
		console.error("facts: out/shared does not exist. Run `npm run build` first.");
		return 1;
	}
	const text = render(gameFacts(), measure("out"));
	if (argv.includes("--check")) {
		const current = fs.existsSync(FACTS_PATH) ? fs.readFileSync(FACTS_PATH, "utf8") : "";
		if (current !== text) {
			console.error(`facts: ${FACTS_PATH} is stale. Run \`npm run facts\` (after a build) and commit it.`);
			return 1;
		}
		console.log(`facts: ${FACTS_PATH} is up to date`);
		return 0;
	}
	fs.writeFileSync(FACTS_PATH, text);
	console.log(`facts: wrote ${FACTS_PATH}`);
	return 0;
}

module.exports = { ANALYTICS_LIMITS, WATCH, localsRows, render };

if (require.main === module) process.exit(main(process.argv.slice(2)));
