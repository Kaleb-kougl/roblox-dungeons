// (the Forge and the room encounters are untouched), every placement rule, the floor stays reachable, counts per depth
// band, and the floor's spawn tiles lose the taken cells. Census: runs 1-20 x floors 1-5 (endlessFloorParams), plus a
// deeper sample for the bands.
