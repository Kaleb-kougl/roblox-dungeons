import { PEDESTAL_RADIUS, SHRINE_RADIUS, STAIRWELL_RADIUS } from "shared/sim";

const dungeons = new Map<string, Dungeon>();
function dungeonFor(params: ForgeParams): Dungeon {
	const key = `${params.seed}/${params.roomCount}`;
	let d = dungeons.get(key);
	if (d === undefined) {
		d = generateDungeon(params);
		dungeons.set(key, d);
	}
	return d;
}

const CENSUS: EndlessFloorLayout[] = [];
for (let run = 1; run <= 20; run++)
	for (let floor = 1; floor <= 5; floor++) CENSUS.push(buildEndlessFloor(run, floor, dungeonFor));

/** A deeper sample: one floor per band step for a few runs (floors 6..20). */
const DEEP: EndlessFloorLayout[] = [];
for (let run = 1; run <= 4; run++)
	for (const floor of [6, 9, 11, 14, 16, 19]) DEEP.push(buildEndlessFloor(run, floor, dungeonFor));

const ALL = [...CENSUS, ...DEEP];

function pieces(l: EndlessFloorLayout): ReadonlyArray<BreakablePlacement> {
	return l.breakables ?? [];
}

function dist2(ax: number, az: number, bx: number, bz: number): number {
	return (ax - bx) * (ax - bx) + (az - bz) * (az - bz);
}

/** 4-neighbour BFS from the entrance centre over FLOOR minus `blocked` cells: reached cell indices. */
function reach(d: Dungeon, blocked: ReadonlySet<number>): boolean[] {
	const e = d.rooms[d.entrance];
	const seen = new Array<boolean>(d.W * d.H, false);
	const q: number[] = [e.cy * d.W + e.cx];
	seen[q[0]] = true;
	let h = 0;
	while (h < q.size()) {
		const c = q[h++];
		const x = c % d.W;
		const y = math.floor(c / d.W);
		for (const [ox, oy] of [
			[1, 0],
			[-1, 0],
			[0, 1],
			[0, -1],
		]) {
			const nx = x + ox;
			const ny = y + oy;
			if (tileAt(d, nx, ny) !== TileType.FLOOR) continue;
			const n = ny * d.W + nx;
			if (seen[n] || blocked.has(n)) continue;
			seen[n] = true;
			q.push(n);
		}
	}
	return seen;
}

function roomOf(l: EndlessFloorLayout, b: BreakablePlacement): EncounterRoom {
	return l.encounter.rooms[l.dungeon.roomId[b.y * l.dungeon.W + b.x]];
}

describe("breakable placement: stream and determinism", () => {
	it("is a pure function of the floor: the same floor always gets the same pieces", () => {
		for (let k = 0; k < 10; k++) {
			const l = CENSUS[k * 7];
			const again = placeBreakables(l, l.floor);
			expect(again).toEqual(pieces(l));
			// From a freshly generated dungeon too (nothing cached or mutated).
			const fresh = buildEndlessFloor(1 + math.floor((k * 7) / 5), ((k * 7) % 5) + 1, (p) => generateDungeon(p));
			expect(fresh.breakables).toEqual(l.breakables);
		}
	});

	it("draws from its own stream: hash(floor seed, salt), never a room encounter seed", () => {
		expect(breakableSeed(12345)).toBe(bit32.bxor(12345, BREAKABLE.salt));
		for (const l of CENSUS.filter((_l, i) => i % 10 === 0)) {
			const s = breakableSeed(l.seed);
			expect(s).never.toBe(l.seed);
			for (let id = 0; id < 64; id++) expect(s).never.toBe(encounterRoomSeed(l.dungeon.seed, id));
		}
	});

	it("leaves the Forge layout, the encounter and the room spawns exactly as before", () => {
		for (const l of CENSUS.filter((_l, i) => i % 9 === 0)) {
			const d = l.dungeon;
			// The dungeon is generated by the Forge alone (placement never writes it) ...
			const fresh = generateDungeon(d.params);
			let diff = 0;
			for (let i = 0; i < d.grid.size(); i++)
				if (fresh.grid[i] !== d.grid[i] || fresh.roomId[i] !== d.roomId[i]) diff++;
			expect(diff).toBe(0);
			expect(fresh.props.size()).toBe(d.props.size());
			expect(fresh.spawns.size()).toBe(d.spawns.size());
			// ... and the spawn tiles are the floor's own minus the taken cells.
			const tiles = endlessRoomSpawnTiles(d, l.roomSpawns);
			const want = withoutBreakableCells(tiles, pieces(l));
			let same = l.roomSpawnTiles.size() === want.size();
			let left = 0;
			let inPiece = 0;
			const taken = new Set<string>();
			for (const b of pieces(l)) taken.add(`${gridToWorld(b.x)},${gridToWorld(b.y)}`);
			for (let r = 0; r < want.size(); r++) {
				const got = l.roomSpawnTiles[r];
				if (got.size() !== want[r].size()) same = false;
				for (let k = 0; k < got.size(); k++) {
					if (got[k].x !== want[r][k]?.x || got[k].z !== want[r][k]?.z) same = false;
					if (taken.has(`${got[k].x},${got[k].z}`)) inPiece++;
				}
				left += tiles[r].size() - got.size();
			}
			expect([same, inPiece]).toEqual([true, 0]);
			// Exactly the taken cells left the lists (each was a spawn tile of at most one room).
			expect(left).toBeLessThanOrEqual(pieces(l).size());
		}
	});

	it("the floor has pieces: most census floors get some, both kinds appear", () => {
		let withPieces = 0;
		let barrels = 0;
		let crates = 0;
		for (const l of CENSUS) {
			if (pieces(l).size() > 0) withPieces++;
			for (const b of pieces(l)) {
				if (b.kind === BREAKABLE_KINDS[0]) barrels++;
				else if (b.kind === BREAKABLE_KINDS[1]) crates++;
			}
		}
		expect(withPieces).toBeGreaterThan(CENSUS.size() * 0.9);
		expect(barrels).toBeGreaterThan(0);
		let total = 0;
		for (const l of CENSUS) total += pieces(l).size();
		expect(barrels + crates).toBe(total);
		expect(crates).toBeGreaterThan(0);
	});
});

describe("breakable placement: the rules (every census floor)", () => {
	it("tunables match the sim's zones: stairwell radius + 1, the shrine zone + 1, the pedestal + 1.5", () => {
		expect(BREAKABLE.stairwellClearTiles).toBe(STAIRWELL_RADIUS + 1);
		expect(BREAKABLE.shrineClearTiles).toBe(SHRINE_RADIUS + 1);
		expect(BREAKABLE.pedestalClearTiles).toBe(PEDESTAL_RADIUS + 1.5);
	});

	// Each rule collects its violations (one expect per rule: thousands of expect calls are slow headlessly).

	it("only room FLOOR cells of combat / elite / treasure rooms, never corridors, doorways or two on one cell", () => {
		const bad: string[] = [];
		for (const l of ALL) {
			const d = l.dungeon;
			const seen = new Set<number>();
			for (const b of pieces(l)) {
				const i = b.y * d.W + b.x;
				const room = roomOf(l, b);
				const at = `${l.seed}:${b.x},${b.y}`;
				if (tileAt(d, b.x, b.y) !== TileType.FLOOR) bad.push(`${at} not FLOOR`);
				if (d.corridor[i] !== 0 || d.doorway[i] !== 0) bad.push(`${at} corridor / doorway`);
				if (!["combat", "elite", "treasure"].includes(room.type)) bad.push(`${at} in a ${room.type} room`);
				if (room.id === d.entrance || room.id === d.boss) bad.push(`${at} entrance / boss room`);
				if (seen.has(i)) bad.push(`${at} twice`);
				seen.add(i);
			}
		}
		expect(bad).toEqual([]);
	});

	it("keeps clear of doorways, spawns, the entrance, the stairwell, pedestals, the shrine and pools", () => {
		const bad: string[] = [];
		const near = (at: string, what: string, x: number, z: number, px: number, pz: number, r: number) => {
			if (dist2(x, z, px, pz) < r * r) bad.push(`${at} near ${what}`);
		};
		for (const l of ALL) {
			const d = l.dungeon;
			const doors = new Map<number, ReturnType<typeof roomDoorways>>();
			for (const b of pieces(l)) {
				const room = roomOf(l, b);
				const x = gridToWorld(b.x);
				const z = gridToWorld(b.y);
				const at = `${l.seed}:${b.x},${b.y}`;
				let roomDoors = doors.get(room.id);
				if (roomDoors === undefined) {
					roomDoors = roomDoorways(d, room.id);
					doors.set(room.id, roomDoors);
				}
				for (const door of roomDoors) near(at, "a door", x, z, door.x, door.z, BREAKABLE.doorClearTiles);
				for (const spawns of l.roomSpawns)
					for (const sp of spawns) near(at, "a spawn", x, z, sp.x, sp.z, BREAKABLE.spawnClearTiles);
				for (const sp of l.encounter.spawns) near(at, "the boss", x, z, sp.x, sp.z, BREAKABLE.spawnClearTiles);
				near(at, "the entrance", x, z, l.spawn.x, l.spawn.z, BREAKABLE.entranceClearTiles);
				near(at, "the stairwell", x, z, l.stairwell.x, l.stairwell.z, BREAKABLE.stairwellClearTiles);
				for (const r of l.encounter.rooms) {
					if (r.type === "treasure") near(at, "a pedestal", x, z, r.cx, r.cz, BREAKABLE.pedestalClearTiles);
					if (r.type === "shrine") near(at, "a shrine", x, z, r.cx, r.cz, BREAKABLE.shrineClearTiles);
				}
				for (let oy = -1; oy <= 1; oy++)
					for (let ox = -1; ox <= 1; ox++)
						if (tileAt(d, b.x + ox, b.y + oy) === TileType.POOL) bad.push(`${at} next to a pool`);
			}
		}
		expect(bad).toEqual([]);
	});

	it("no new pinch points: two solids touch or leave >= minGapTiles (same-obstacle nooks aside)", () => {
		const bad: string[] = [];
		for (const l of ALL) {
			const d = l.dungeon;
			const taken = new Set<number>();
			for (const b of pieces(l)) taken.add(b.y * d.W + b.x);
			const solid = (x: number, y: number) => tileAt(d, x, y) !== TileType.FLOOR || taken.has(y * d.W + x);
			for (const b of pieces(l))
				for (let oy = -2; oy <= 2; oy++)
					for (let ox = -2; ox <= 2; ox++) {
						if (math.max(math.abs(ox), math.abs(oy)) !== 2) continue;
						if (!solid(b.x + ox, b.y + oy)) continue;
						// Gap < 2 at Chebyshev distance 2: allowed only through a solid touching both.
						let joined = false;
						for (let ty = -1; ty <= 1; ty++)
							for (let tx = -1; tx <= 1; tx++) {
								if (tx === 0 && ty === 0) continue;
								const cx = b.x + tx;
								const cy = b.y + ty;
								if (math.abs(cx - (b.x + ox)) <= 1 && math.abs(cy - (b.y + oy)) <= 1 && solid(cx, cy))
									joined = true;
							}
						if (!joined) bad.push(`${l.seed}:${b.x},${b.y} gap to ${ox},${oy}`);
					}
		}
		expect(bad).toEqual([]);
	});

	it("reachability: every floor cell the floor's BFS reached is still reached without the pieces' cells", () => {
		const bad: string[] = [];
		for (const l of ALL) {
			const d = l.dungeon;
			const before = reach(d, new Set());
			const taken = new Set<number>();
			for (const b of pieces(l)) taken.add(b.y * d.W + b.x);
			const after = reach(d, taken);
			let lost = 0;
			for (let i = 0; i < before.size(); i++) if (before[i] && !taken.has(i) && !after[i]) lost++;
			if (lost > 0) bad.push(`${l.seed}: ${lost} cells cut off`);
		}
		expect(bad).toEqual([]);
	});

	it("shape: clusters of at most clusterMax hugging a wall, at most one lone mid-room piece per big combat room", () => {
		const bad: string[] = [];
		let lones = 0;
		let clusters = 0;
		for (const l of ALL) {
			const d = l.dungeon;
			const list = pieces(l);
			const at = new Map<number, number>();
			for (let k = 0; k < list.size(); k++) at.set(list[k].y * d.W + list[k].x, k);
			const group = new Array<number>(list.size(), -1);
			const lonesPerRoom = new Map<number, number>();
			for (let k = 0; k < list.size(); k++) {
				if (group[k] >= 0) continue;
				// 8-connected component (groups never touch, so this is one cluster or the lone piece).
				const members = [k];
				group[k] = k;
				let h = 0;
				while (h < members.size()) {
					const m = list[members[h++]];
					for (let oy = -1; oy <= 1; oy++)
						for (let ox = -1; ox <= 1; ox++) {
							const j = at.get((m.y + oy) * d.W + m.x + ox);
							if (j !== undefined && group[j] < 0) {
								group[j] = k;
								members.push(j);
							}
						}
				}
				const tag = `${l.seed}:${list[k].x},${list[k].y}`;
				// a storeroom's clusters are bigger (docs/DECOR.md "Room themes")
				const store = (d.roomThemes ?? [])[roomOf(l, list[k]).id] === "store";
				const most = store ? BREAKABLE.store.clusterMax : BREAKABLE.clusterMax;
				if (members.size() > most) bad.push(`${tag} cluster of ${members.size()}`);
				const hugs = members.some((j) => {
					const b = list[j];
					return [
						[1, 0],
						[-1, 0],
						[0, 1],
						[0, -1],
					].some(([ox, oy]) => tileAt(d, b.x + ox, b.y + oy) === TileType.WALL);
				});
				if (hugs) {
					clusters++;
					continue;
				}
				// The lone mid-room piece: alone, in a combat room large enough both ways, clear of walls.
				lones++;
				const b = list[k];
				const room = roomOf(l, b);
				if (members.size() !== 1) bad.push(`${tag} a free-standing group of ${members.size()}`);
				if (room.type !== "combat") bad.push(`${tag} lone piece in a ${room.type} room`);
				if (
					room.maxX - room.minX < BREAKABLE.loneMinRoomSide ||
					room.maxZ - room.minZ < BREAKABLE.loneMinRoomSide
				)
					bad.push(`${tag} lone piece in a small room`);
				const r = BREAKABLE.loneWallClearTiles;
				for (let oy = -r; oy <= r; oy++)
					for (let ox = -r; ox <= r; ox++)
						if (tileAt(d, b.x + ox, b.y + oy) !== TileType.FLOOR) bad.push(`${tag} lone piece near a wall`);
				lonesPerRoom.set(room.id, (lonesPerRoom.get(room.id) ?? 0) + 1);
			}
			lonesPerRoom.forEach((n, id) => {
				if (n > 1) bad.push(`${l.seed}: room ${id} has ${n} lone pieces`);
			});
		}
		expect(bad).toEqual([]);
		expect(lones).toBeGreaterThan(0);
		expect(clusters).toBeGreaterThan(lones);
	});

	it("candidates: breakableCandidates holds every piece of its room", () => {
		const bad: string[] = [];
		for (const l of CENSUS.filter((_l, i) => i % 11 === 0)) {
			for (const b of pieces(l)) {
				const c = breakableCandidates(l, roomOf(l, b));
				if (!c.some((t) => t.x === b.x && t.z === b.y)) bad.push(`${l.seed}:${b.x},${b.y}`);
			}
		}
		expect(bad).toEqual([]);
	});
});

describe("breakable placement: counts per depth band", () => {
	it("bands: kept 1-4, worn 5-9, ruined 10-14, abyss 15+", () => {
		const names = [1, 4, 5, 9, 10, 14, 15, 40].map((f) => breakableBand(f).name);
		expect(names).toEqual(["kept", "kept", "worn", "worn", "ruined", "ruined", "abyss", "abyss"]);
		expect(breakableRoomCount(2, BREAKABLE.referenceRoomTiles)).toBe(2);
		expect(breakableRoomCount(6, BREAKABLE.referenceRoomTiles * 100)).toBe(BREAKABLE.maxPerRoom);
		expect(breakableRoomCount(0, 10000)).toBe(0);
	});

	it("no room gets more than its band's max x area (capped; a storeroom x countScale + countExtra, a mess hall x mess.countScale); averages grow band by band", () => {
		const perBand = new Map<string, { rooms: number; pieces: number }>();
		let over = 0;
		for (const l of ALL) {
			const band = breakableBand(l.floor);
			const byRoom = new Map<number, number>();
			for (const b of pieces(l)) {
				const id = roomOf(l, b).id;
				byRoom.set(id, (byRoom.get(id) ?? 0) + 1);
			}
			for (const room of l.encounter.rooms) {
				if (!["combat", "elite", "treasure"].includes(room.type)) continue;
				if (room.id === l.dungeon.entrance || room.id === l.dungeon.boss) continue;
				const n = byRoom.get(room.id) ?? 0;
				const most = breakableRoomCount(band.max, room.floorTiles);
				const S = BREAKABLE.store;
				const theme = (l.dungeon.roomThemes ?? [])[room.id];
				const cap =
					theme === "store"
						? math.min(BREAKABLE.maxPerRoom, most * S.countScale + S.countExtra)
						: theme === "mess"
						? math.min(BREAKABLE.maxPerRoom, math.floor(most * BREAKABLE.mess.countScale))
						: most;
				if (n > cap) over++;
				const e = perBand.get(band.name) ?? { rooms: 0, pieces: 0 };
				e.rooms++;
				e.pieces += n;
				perBand.set(band.name, e);
			}
		}
		const avg = (name: string) => {
			const e = perBand.get(name)!;
			return e.pieces / e.rooms;
		};
		const kept = avg("kept");
		const worn = avg("worn");
		const ruined = avg("ruined");
		const abyss = avg("abyss");
		print(
			`[breakables] pieces per room: kept ${string.format("%.2f", kept)}, worn ${string.format(
				"%.2f",
				worn,
			)}, ruined ${string.format("%.2f", ruined)}, abyss ${string.format("%.2f", abyss)}`,
		);
		let total = 0;
		for (const l of CENSUS) total += pieces(l).size();
		print(`[breakables] census: ${total / CENSUS.size()} pieces per floor (runs 1-20, floors 1-5)`);
		expect(over).toBe(0);
		expect(kept).toBeGreaterThan(0);
		expect(worn).toBeGreaterThan(kept);
		expect(ruined).toBeGreaterThan(worn);
		expect(abyss).toBeGreaterThan(ruined);
	});
});

describe("collision with solid cells (the sim's intact breakables)", () => {
	const l = CENSUS[0];
	const d = l.dungeon;
	const b = pieces(l)[0];
	const solid = new Map<number, number>([[cellKey(b.x, b.y), 0]]);
	const bx = gridToWorld(b.x);
	const bz = gridToWorld(b.y);

	it("absent, every function is exactly the grid-only one; present, the cell blocks circles and bullets", () => {
		const mover = circleMover(d, 0.35);
		const steer = actorSteerMover(d);
		let same = 0;
		let total = 0;
		for (let k = 0; k < 64; k++) {
			const ox = ((k % 8) - 3.5) * 0.4;
			const oz = (math.floor(k / 8) - 3.5) * 0.4;
			const dx = -ox * 0.05;
			const dz = -oz * 0.05;
			const a = moveCircle(d, bx + ox, bz + oz, dx, dz, 0.35);
			const p = mover(bx + ox, bz + oz, dx, dz, undefined);
			const q = moveCircleAroundCorners(d, bx + ox, bz + oz, dx, dz, 0.35);
			const r = steer(bx + ox, bz + oz, dx, dz, 0.35, undefined);
			total++;
			if (a.x === p.x && a.z === p.z && q.x === r.x && q.z === r.z) same++;
		}
		expect(same).toBe(total);
		expect(isBulletBlocked(d, bx, bz)).toBe(false);
		expect(isBulletBlocked(d, bx, bz, solid)).toBe(true);
		expect(bulletBlocker(d)(bx + 0.4, bz - 0.4, solid)).toBe(true);
		expect(circleOverlapsWall(d, bx, bz, 0.3, undefined, solid)).toBe(true);
		// A circle walking at the cell stops at its face.
		const hit = moveCircle(d, bx - 1.2, bz, 0.1, 0, 0.35, solid);
		expect(moveCircle(d, hit.x, bz, 0.5, 0, 0.35, solid).x).toBeCloseTo(bx - 0.5 - 0.35, 9);
	});

	it("line of sight never sees them (B2: low cover)", () => {
		const blocker = bulletBlocker(d);
		expect(lineOfSight(blocker, bx - 2, bz, bx + 2, bz)).toBe(
			lineOfSight((x, z) => isBulletBlocked(d, x, z), bx - 2, bz, bx + 2, bz),
		);
	});
});
