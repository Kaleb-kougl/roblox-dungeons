// The vale pack's sounds (docs/FX_AUDIO.md A1): the generated audio layout (npm run audio:build) fits the contract and the
// Roblox upload limits, and a sound ID switches from SILENT to its clips only once every one of its files has an ID.
import { describe, expect, it } from "@rbxts/jest-globals";
import { AMBIENCE, MUSIC, REQUIRED_ASSET_IDS, slotFor } from "../../contract";
import { ThemePack } from "../../pack";
import type { SoundAsset } from "../../types";
import { sortedKeys } from "../../util";
import { validateManifest } from "../../validate";
import { PLACEHOLDER_MANIFEST } from "../placeholder";
import { VALE_ASSET_IDS } from "./assetIds";
import { VALE_AUDIO_FILES, VALE_SOUND_LAYOUTS } from "./audioLayout";
import { buildValeManifest, VALE_MANIFEST } from "./manifest";

const quiet = () => undefined;

/** Roblox audio upload limits (art/audio.json `limits`; the build fails past them). */
const MAX_SECONDS = 420;
const MAX_SAMPLE_RATE = 48000;

/** A fake uploaded ID for every built audio file (test vectors; src/shared/theme is exempt from check-asset-ids). */
function audioIds(...skip: Array<string>): Record<string, string> {
	const ids: Record<string, string> = {};
	sortedKeys(VALE_AUDIO_FILES).forEach((file, i) => {
		if (!skip.includes(file)) {
			ids[file] = `rbxassetid://${7000 + i}`;
		}
	});
	return ids;
}

/** A sound ID of the layout with more than one clip (the variant rule needs one). */
function firstPooledId(): string {
	for (const id of sortedKeys(VALE_SOUND_LAYOUTS)) {
		if (VALE_SOUND_LAYOUTS[id].files.size() > 1) {
			return id;
		}
	}
	error("no sound ID with variants in the layout", 0);
}

describe("vale audio layout (generated by npm run audio:build)", () => {
	it("lists only required sound IDs, every file built and within the Roblox upload limits", () => {
		const listed = new Set<string>();
		for (const id of sortedKeys(VALE_SOUND_LAYOUTS)) {
			const layout = VALE_SOUND_LAYOUTS[id];
			const slot = slotFor(id);
			expect([id, REQUIRED_ASSET_IDS.includes(id), slot !== undefined && slot.kinds.includes("sound")]).toEqual([
				id,
				true,
				true,
			]);
			expect([id, layout.files.size() > 0, layout.volume >= 0 && layout.volume <= 1]).toEqual([id, true, true]);
			// Music and ambience loop one clip at speed 1 (the validator rejects variants / pitch there).
			if (slot === MUSIC || slot === AMBIENCE) {
				expect([id, layout.files.size(), layout.pitch]).toEqual([id, 1, undefined]);
			}
			for (const file of layout.files) {
				expect([id, file, VALE_AUDIO_FILES[file] !== undefined, listed.has(file)]).toEqual([
					id,
					file,
					true,
					false,
				]);
				listed.add(file);
			}
		}
		for (const file of sortedKeys(VALE_AUDIO_FILES)) {
			const f = VALE_AUDIO_FILES[file];
			expect([file, listed.has(file)]).toEqual([file, true]);
			expect([file, f.seconds > 0, f.seconds < MAX_SECONDS, f.sampleRate <= MAX_SAMPLE_RATE]).toEqual([
				file,
				true,
				true,
				true,
			]);
			expect([file, f.channels === 1 || f.channels === 2]).toEqual([file, true]);
		}
	});
});

describe("vale sounds switch on with their uploads", () => {
	it("with no audio IDs every sound stays the placeholder's SILENT", () => {
		const m = buildValeManifest({});
		for (const id of sortedKeys(VALE_SOUND_LAYOUTS)) {
			expect([id, m.assets[id]]).toEqual([id, PLACEHOLDER_MANIFEST.assets[id]]);
			expect([id, m.assets[id].kind]).toEqual([id, "silent"]);
		}
	});

	it("as bundled, a sound plays only when every one of its files has an ID (none half-uploaded)", () => {
		for (const id of sortedKeys(VALE_SOUND_LAYOUTS)) {
			const all = VALE_SOUND_LAYOUTS[id].files.every((f) => VALE_ASSET_IDS[f] !== undefined);
			expect([id, VALE_MANIFEST.assets[id].kind]).toEqual([id, all ? "sound" : "silent"]);
		}
	});

	it("with every file uploaded each ID is a sound: files[0] the assetId, the rest variants, the layout's extras", () => {
		const ids = audioIds();
		const m = buildValeManifest(ids);
		expect(validateManifest(m, { packId: "vale" })).toEqual([]);
		const pack = new ThemePack(m, { warn: quiet });
		for (const id of sortedKeys(VALE_SOUND_LAYOUTS)) {
			const layout = VALE_SOUND_LAYOUTS[id];
			const expected: SoundAsset = {
				kind: "sound",
				assetId: ids[layout.files[0]] as SoundAsset["assetId"],
				volume: layout.volume,
			};
			if (layout.files.size() > 1) {
				expected.variants = layout.files.filter((_, i) => i > 0).map((f) => ids[f] as SoundAsset["assetId"]);
			}
			if (layout.pitch !== undefined) expected.pitch = [layout.pitch[0], layout.pitch[1]];
			if (layout.minInterval !== undefined) expected.minInterval = layout.minInterval;
			expect([id, m.assets[id]]).toEqual([id, expected]);
			const ref = pack.sound(id);
			expect([id, ref.assetId, ref.variants.size(), ref.volume]).toEqual([
				id,
				ids[layout.files[0]],
				layout.files.size() - 1,
				layout.volume,
			]);
			expect([id, ref.group]).toEqual([id, slotFor(id)!.soundGroup]);
		}
		// IDs the layout leaves out (art/audio.json "silent") stay silent
		for (const id of sortedKeys(PLACEHOLDER_MANIFEST.assets)) {
			if (VALE_SOUND_LAYOUTS[id] === undefined && PLACEHOLDER_MANIFEST.assets[id].kind === "silent") {
				expect([id, m.assets[id].kind]).toEqual([id, "silent"]);
			}
		}
	});

	it("one missing variant keeps its ID silent; the other IDs switch", () => {
		const id = firstPooledId();
		const missing = VALE_SOUND_LAYOUTS[id].files[1];
		const m = buildValeManifest(audioIds(missing));
		expect(validateManifest(m, { packId: "vale" })).toEqual([]);
		expect(m.assets[id]).toEqual({ kind: "silent" });
		for (const other of sortedKeys(VALE_SOUND_LAYOUTS)) {
			if (other !== id) expect([other, m.assets[other].kind]).toEqual([other, "sound"]);
		}
		const pack = new ThemePack(m, { warn: quiet });
		expect(pack.sound(id).assetId).toBe(undefined);
	});

	it("is deterministic and never mutates the placeholder manifest", () => {
		expect(buildValeManifest(audioIds())).toEqual(buildValeManifest(audioIds()));
		for (const id of sortedKeys(VALE_SOUND_LAYOUTS)) {
			expect([id, PLACEHOLDER_MANIFEST.assets[id].kind]).toEqual([id, "silent"]);
		}
	});
});

describe("vale draft reveal sounds (docs/DRAFT_REVEAL.md DR4)", () => {
	const DRAFT = ["sfx.draft.flip", "sfx.draft.rare", "sfx.draft.charge", "sfx.draft.legendary", "sfx.draft.pick"];

	it("are required sfx IDs, silent until audio:build lays them out and their files are uploaded", () => {
		for (const id of DRAFT) {
			expect([id, REQUIRED_ASSET_IDS.includes(id), slotFor(id)?.soundGroup]).toEqual([id, true, "sfx"]);
			expect([id, PLACEHOLDER_MANIFEST.assets[id].kind]).toEqual([id, "silent"]);
			// not built yet (the owner picks the candidates at the audition): no layout, so silent whatever the IDs
			if (VALE_SOUND_LAYOUTS[id] === undefined) {
				expect([id, buildValeManifest(audioIds()).assets[id].kind]).toEqual([id, "silent"]);
			}
			const all = VALE_SOUND_LAYOUTS[id]?.files.every((f) => VALE_ASSET_IDS[f] !== undefined) ?? false;
			expect([id, VALE_MANIFEST.assets[id].kind]).toEqual([id, all ? "sound" : "silent"]);
		}
	});
});
